<?php

namespace App\Http\Controllers;

use App\Models\Branch;
use App\Models\Category;
use App\Models\InventoryItem;
use App\Models\ItemInventory;
use Carbon\Carbon;
use Illuminate\Http\Request;
use Illuminate\Support\Collection;
use Illuminate\Support\Facades\DB;

/**
 * Item Stock Balance report, branch-wise, with item movement.
 *
 * Built from the item_inventory ledger. Quantities are stored positive and
 * the direction comes from transaction_type:
 *   in  : receive, issue_return, sell_return
 *   out : issue, sell
 *
 * For the selected period it shows, per branch + item:
 *   Opening (before "from") + Received + Issue Returned + Sell Returned
 *   - Issued - Sold = Closing (at "to").
 * Clicking "Movement" on a row lists every ledger entry for that item and
 * branch in the period with a running balance.
 */
class ItemStockReportController extends Controller
{
    private const IN_TYPES = ['receive', 'issue_return', 'sell_return'];

    private const TYPE_LABELS = [
        'receive' => 'Received',
        'issue' => 'Issued',
        'issue_return' => 'Issue Returned',
        'sell' => 'Sold',
        'sell_return' => 'Sell Returned',
    ];

    public function index(Request $request)
    {
        [$from, $to] = $this->period($request);

        $branches = Branch::orderBy('name')->get(['id', 'name']);
        $categories = Category::orderBy('name')->get(['id', 'name']);
        $items = InventoryItem::orderBy('item_name')->get(['id', 'item_name']);

        $rows = $this->summaryRows($request, $from, $to);
        $byBranch = $rows->groupBy('branch_name');

        $movement = null;
        if ($request->filled('movement_item_id')) {
            $movement = $this->movementRows(
                (int) $request->movement_item_id,
                $request->input('movement_branch_id'),
                $from,
                $to
            );
        }

        return view('pages.reports.item-stock', compact(
            'branches', 'categories', 'items', 'rows', 'byBranch', 'movement', 'from', 'to'
        ));
    }

    public function export(Request $request)
    {
        [$from, $to] = $this->period($request);
        $isMovement = $request->filled('movement_item_id');

        $filename = ($isMovement ? 'Item-Movement_' : 'Item-Stock-Balance_') . now()->format('Y-m-d_His') . '.csv';

        return response()->streamDownload(function () use ($request, $from, $to, $isMovement) {
            $h = fopen('php://output', 'w');
            fwrite($h, "\xEF\xBB\xBF");
            fputcsv($h, ['Report', $isMovement ? 'Item Movement' : 'Item Stock Balance (Branch-wise)']);
            fputcsv($h, ['Period', $from->toDateString() . ' to ' . $to->toDateString()]);
            fputcsv($h, ['Generated At', now()->format('Y-m-d h:i A')]);
            fputcsv($h, ['Generated By', optional(auth()->user())->name ?? '-']);
            fputcsv($h, []);

            if ($isMovement) {
                $m = $this->movementRows((int) $request->movement_item_id, $request->input('movement_branch_id'), $from, $to);
                fputcsv($h, ['Item', $m['item_name'], 'Branch', $m['branch_name']]);
                fputcsv($h, ['Date', 'Type', 'In', 'Out', 'Balance', 'Reference', 'Description']);
                fputcsv($h, [$from->toDateString(), 'Opening balance', '', '', $m['opening'], '', '']);
                foreach ($m['rows'] as $r) {
                    fputcsv($h, [$r['date'], $r['type'], $r['in'] ?: '', $r['out'] ?: '', $r['balance'], $r['reference'], $r['description']]);
                }
                fputcsv($h, [$to->toDateString(), 'Closing balance', $m['total_in'], $m['total_out'], $m['closing'], '', '']);
            } else {
                fputcsv($h, ['Branch', 'Category', 'Item', 'Opening', 'Received', 'Issue Returned', 'Sell Returned', 'Issued', 'Sold', 'Closing', 'Unit Price', 'Closing Value']);
                foreach ($this->summaryRows($request, $from, $to) as $r) {
                    fputcsv($h, [
                        $r['branch_name'], $r['category_name'], $r['item_name'], $r['opening'], $r['receive'],
                        $r['issue_return'], $r['sell_return'], $r['issue'], $r['sell'], $r['closing'],
                        number_format($r['unit_price'], 2, '.', ''), number_format($r['closing_value'], 2, '.', ''),
                    ]);
                }
            }

            fclose($h);
        }, $filename, ['Content-Type' => 'text/csv']);
    }

    /** [from, to] — defaults to the current month. */
    private function period(Request $request): array
    {
        if ($request->filled('date_range')) {
            $parts = explode(' to ', $request->date_range);
            $from = Carbon::parse(trim($parts[0]))->startOfDay();
            $to = Carbon::parse(trim($parts[1] ?? $parts[0]))->endOfDay();
        } else {
            $from = now()->startOfMonth();
            $to = now()->endOfDay();
        }

        return [$from, $to];
    }

    private function signedQty(): string
    {
        return "CASE WHEN ii.transaction_type IN ('" . implode("','", self::IN_TYPES) . "') THEN ii.quantity ELSE -ii.quantity END";
    }

    private function summaryRows(Request $request, Carbon $from, Carbon $to): Collection
    {
        $signed = $this->signedQty();
        $fromDate = $from->toDateString();
        $toDate = $to->toDateString();

        $rows = DB::table('item_inventory as ii')
            ->join('inventory_items as it', 'it.id', '=', 'ii.item_id')
            ->leftJoin('categories as cat', 'cat.id', '=', 'it.item_category_id')
            ->leftJoin('branches as b', 'b.id', '=', 'ii.branch_id')
            ->whereDate('ii.transaction_date', '<=', $toDate)
            ->when($request->filled('branch_id'), fn($q) => $q->where('ii.branch_id', $request->branch_id))
            ->when($request->filled('category_id'), fn($q) => $q->where('it.item_category_id', $request->category_id))
            ->when($request->filled('item_id'), fn($q) => $q->where('ii.item_id', $request->item_id))
            ->groupBy('ii.branch_id', 'b.name', 'ii.item_id', 'it.item_name', 'it.item_price', 'cat.name')
            ->select(
                'ii.branch_id', 'b.name as branch_name', 'ii.item_id', 'it.item_name', 'it.item_price', 'cat.name as category_name',
                DB::raw("SUM(CASE WHEN DATE(ii.transaction_date) < '{$fromDate}' THEN {$signed} ELSE 0 END) as opening"),
                DB::raw("SUM(CASE WHEN DATE(ii.transaction_date) >= '{$fromDate}' AND ii.transaction_type = 'receive' THEN ii.quantity ELSE 0 END) as receive_qty"),
                DB::raw("SUM(CASE WHEN DATE(ii.transaction_date) >= '{$fromDate}' AND ii.transaction_type = 'issue' THEN ii.quantity ELSE 0 END) as issue_qty"),
                DB::raw("SUM(CASE WHEN DATE(ii.transaction_date) >= '{$fromDate}' AND ii.transaction_type = 'issue_return' THEN ii.quantity ELSE 0 END) as issue_return_qty"),
                DB::raw("SUM(CASE WHEN DATE(ii.transaction_date) >= '{$fromDate}' AND ii.transaction_type = 'sell' THEN ii.quantity ELSE 0 END) as sell_qty"),
                DB::raw("SUM(CASE WHEN DATE(ii.transaction_date) >= '{$fromDate}' AND ii.transaction_type = 'sell_return' THEN ii.quantity ELSE 0 END) as sell_return_qty"),
                DB::raw("SUM({$signed}) as closing")
            )
            ->orderByRaw('b.name IS NULL, b.name')
            ->orderBy('it.item_name')
            ->get();

        // Stored running balance the app itself uses when selling/issuing
        // (ItemInventory::getCurrentBalance). Only comparable when the period
        // runs up to today. A difference means the stored balance drifted
        // from the real movements and should be checked.
        $compareSystem = $to->greaterThanOrEqualTo(now()->startOfDay());

        return $rows->map(function ($r) use ($compareSystem) {
            $closing = (int) $r->closing;
            $moved = (int) $r->receive_qty + (int) $r->issue_qty + (int) $r->issue_return_qty + (int) $r->sell_qty + (int) $r->sell_return_qty;

            return [
                'branch_id' => $r->branch_id,
                'branch_name' => $r->branch_name ?? 'No branch',
                'item_id' => $r->item_id,
                'item_name' => $r->item_name,
                'category_name' => $r->category_name ?? '-',
                'opening' => (int) $r->opening,
                'receive' => (int) $r->receive_qty,
                'issue' => (int) $r->issue_qty,
                'issue_return' => (int) $r->issue_return_qty,
                'sell' => (int) $r->sell_qty,
                'sell_return' => (int) $r->sell_return_qty,
                'closing' => $closing,
                'moved' => $moved,
                'system_balance' => ($compareSystem && $r->branch_id !== null)
                    ? (int) ItemInventory::getCurrentBalance($r->item_id, $r->branch_id)
                    : null,
                'unit_price' => (float) $r->item_price,
                'closing_value' => $closing * (float) $r->item_price,
            ];
        })
            // "hide_zero": skip items with no stock and no movement in the period
            ->when($request->boolean('hide_zero', true), fn($c) => $c->filter(fn($r) => $r['closing'] != 0 || $r['opening'] != 0 || $r['moved'] > 0))
            ->values();
    }

    private function movementRows(int $itemId, $branchId, Carbon $from, Carbon $to): array
    {
        $signed = $this->signedQty();
        $branchFilter = function ($q) use ($branchId) {
            if ($branchId === null || $branchId === '' || $branchId === 'none') {
                $q->whereNull('ii.branch_id');
            } else {
                $q->where('ii.branch_id', $branchId);
            }
        };

        $opening = (int) DB::table('item_inventory as ii')
            ->where('ii.item_id', $itemId)
            ->where($branchFilter)
            ->whereDate('ii.transaction_date', '<', $from->toDateString())
            ->sum(DB::raw($signed));

        $entries = DB::table('item_inventory as ii')
            ->where('ii.item_id', $itemId)
            ->where($branchFilter)
            ->whereDate('ii.transaction_date', '>=', $from->toDateString())
            ->whereDate('ii.transaction_date', '<=', $to->toDateString())
            ->orderBy('ii.transaction_date')
            ->orderBy('ii.id')
            ->get(['ii.id', 'ii.transaction_type', 'ii.transaction_id', 'ii.quantity', 'ii.reference_no', 'ii.transaction_date', 'ii.description']);

        $balance = $opening;
        $totalIn = $totalOut = 0;
        $rows = [];

        foreach ($entries as $e) {
            $isIn = in_array($e->transaction_type, self::IN_TYPES, true);
            $qty = (int) $e->quantity;
            $balance += $isIn ? $qty : -$qty;
            $isIn ? $totalIn += $qty : $totalOut += $qty;

            $rows[] = [
                'date' => Carbon::parse($e->transaction_date)->format('Y-m-d'),
                'type' => self::TYPE_LABELS[$e->transaction_type] ?? ucfirst(str_replace('_', ' ', $e->transaction_type)),
                'is_in' => $isIn,
                'in' => $isIn ? $qty : 0,
                'out' => $isIn ? 0 : $qty,
                'balance' => $balance,
                'reference' => $e->reference_no ?: ('#' . $e->transaction_id),
                'description' => $e->description ?? '',
            ];
        }

        return [
            'item_id' => $itemId,
            'item_name' => optional(InventoryItem::find($itemId))->item_name ?? ('Item #' . $itemId),
            'branch_id' => $branchId,
            'branch_name' => ($branchId && $branchId !== 'none') ? (optional(Branch::find($branchId))->name ?? '-') : 'No branch',
            'opening' => $opening,
            'closing' => $balance,
            'total_in' => $totalIn,
            'total_out' => $totalOut,
            'rows' => $rows,
        ];
    }
}
