<?php

namespace App\Http\Controllers;

use App\Models\Branch;
use App\Models\Course;
use App\Models\Intake;
use Illuminate\Http\Request;
use Illuminate\Pagination\LengthAwarePaginator;
use Illuminate\Support\Collection;
use Illuminate\Support\Facades\DB;

/**
 * NVQ Payment report — every started/completed enrolment in a course that
 * has an NVQ payment, with the student's course completion percentage and
 * their NVQ payment status. By default only students ABOVE 75% completion
 * are listed (the "min_percent" filter changes that).
 *
 * Course completion % = completed subjects / assigned subjects (theory +
 * practical), using the same rules as the Final Assessment Marks /
 * Certificate pages:
 *  - practical subject completed = practice time done >= planned practical_time
 *  - theory subject completed    = attended at least once
 */
class NvqPaymentReportController extends Controller
{
    private const DEFAULT_MIN_PERCENT = 75;

    public function index(Request $request)
    {
        $branches = Branch::orderBy('name')->get();
        $courses = Course::where('has_nvq_payment', 1)->orderBy('name')->get();
        $intakes = Intake::orderByDesc('start_date')->get(['id', 'name']);

        $rows = $this->buildRows($request);

        $summary = [
            'students' => $rows->count(),
            'nvq_total' => $rows->sum('nvq_amount'),
            'nvq_paid' => $rows->sum('nvq_paid'),
            'nvq_due' => $rows->sum('nvq_due'),
            'paid' => $rows->where('nvq_status', 'Paid')->count(),
            'partial' => $rows->where('nvq_status', 'Partial')->count(),
            'not_paid' => $rows->where('nvq_status', 'Not Paid')->count(),
        ];

        $page = LengthAwarePaginator::resolveCurrentPage();
        $perPage = 50;
        $data = new LengthAwarePaginator(
            $rows->slice(($page - 1) * $perPage, $perPage)->values(),
            $rows->count(),
            $perPage,
            $page,
            ['path' => $request->url(), 'query' => $request->query()]
        );

        $minPercent = $this->minPercent($request);

        return view('pages.reports.nvq-payment', compact('data', 'branches', 'courses', 'intakes', 'summary', 'minPercent'));
    }

    public function export(Request $request)
    {
        $rows = $this->buildRows($request);
        $filename = 'NVQ-Payment-Report_' . now()->format('Y-m-d_His') . '.csv';

        $filters = array_filter([
            'Completion above' => $this->minPercent($request) . '%',
            'Branch' => $request->branch_id ? optional(Branch::find($request->branch_id))->name : null,
            'Course' => $request->course_id ? optional(Course::find($request->course_id))->name : null,
            'Intake' => $request->intake_id ? optional(Intake::find($request->intake_id))->name : null,
            'NVQ Status' => $request->nvq_status,
            'Search' => $request->search_text,
        ], fn($v) => $v !== null && $v !== '');

        return response()->streamDownload(function () use ($rows, $filters) {
            $h = fopen('php://output', 'w');
            fwrite($h, "\xEF\xBB\xBF");
            fputcsv($h, ['Report', 'NVQ Payment Report']);
            fputcsv($h, ['Generated At', now()->format('Y-m-d h:i A')]);
            fputcsv($h, ['Generated By', optional(auth()->user())->name ?? '-']);
            foreach ($filters as $label => $value) {
                fputcsv($h, ['', $label, $value]);
            }
            fputcsv($h, []);

            fputcsv($h, [
                'No', 'Student No', 'Student Name', 'NIC', 'Phone', 'Course', 'Intake', 'Intake Start', 'Branch', 'Status',
                'Theory', 'Practical', 'Practice Time (done / required)', 'Completion %',
                'NVQ Amount', 'NVQ Paid', 'NVQ Due', 'NVQ Status', 'Last NVQ Payment',
            ]);

            foreach ($rows->values() as $i => $r) {
                fputcsv($h, [
                    $i + 1, $r['admission_number'], $r['student_name'], $r['nic'], $r['phone'], $r['course_name'],
                    $r['intake_name'], $r['intake_start'], $r['branch_name'], ucfirst($r['status']),
                    $r['theory_done'] . '/' . $r['theory_total'],
                    $r['practical_done'] . '/' . $r['practical_total'],
                    $r['practice_done'] . ' / ' . $r['practice_required'],
                    number_format($r['percent'], 1),
                    number_format($r['nvq_amount'], 2, '.', ''),
                    number_format($r['nvq_paid'], 2, '.', ''),
                    number_format($r['nvq_due'], 2, '.', ''),
                    $r['nvq_status'],
                    $r['last_payment'] ?? '-',
                ]);
            }
            fclose($h);
        }, $filename, ['Content-Type' => 'text/csv']);
    }

    private function minPercent(Request $request): float
    {
        return $request->filled('min_percent') ? (float) $request->min_percent : self::DEFAULT_MIN_PERCENT;
    }

    private function buildRows(Request $request): Collection
    {
        // 1) Enrolments in NVQ courses (a changed course counts as its new course).
        $enrolments = DB::table('student_courses as sc')
            ->join('students as s', 's.id', '=', 'sc.student_id')
            ->join('courses as c', 'c.id', '=', DB::raw('COALESCE(sc.change_course_id, sc.course_id)'))
            ->leftJoin('intakes as i', 'i.id', '=', 'sc.intake_id')
            ->leftJoin('branches as b', 'b.id', '=', 'sc.branch_id')
            ->where('c.has_nvq_payment', 1)
            ->whereIn('sc.status', $request->filled('status') ? [$request->status] : ['start', 'complete'])
            ->when($request->filled('branch_id'), fn($q) => $q->where('sc.branch_id', $request->branch_id))
            ->when($request->filled('intake_id'), fn($q) => $q->where('sc.intake_id', $request->intake_id))
            ->when($request->filled('course_id'), fn($q) => $q->where('c.id', $request->course_id))
            ->when($request->filled('search_text'), function ($q) use ($request) {
                $t = $request->search_text;
                $q->where(fn($w) => $w->where('s.admission_number', 'like', "%{$t}%")
                    ->orWhere('s.student_name', 'like', "%{$t}%")
                    ->orWhere('s.national_id_number', 'like', "%{$t}%")
                    ->orWhere('s.phone_number', 'like', "%{$t}%"));
            })
            ->select(
                'sc.id', 'sc.student_id', 'sc.course_id', 'sc.change_course_id', 'sc.intake_id', 'sc.status',
                's.admission_number', 's.student_name', 's.national_id_number', 's.phone_number',
                'c.id as nvq_course_id', 'c.name as course_name', 'c.nvq_amount as course_nvq_amount',
                'i.name as intake_name', 'i.start_date as intake_start', 'b.name as branch_name'
            )
            ->orderBy('s.admission_number')
            ->get();

        if ($enrolments->isEmpty()) {
            return collect();
        }

        $studentIds = $enrolments->pluck('student_id')->unique()->values();
        $courseIds = $enrolments->pluck('course_id')->unique()->values();

        // 2) Assigned subjects per course+intake (attendance is recorded
        //    against the enrolment's original course_id).
        $assignments = DB::table('assign_subjects as a')
            ->join('subjects as sub', 'sub.id', '=', 'a.subject_id')
            ->whereIn('a.course_id', $courseIds)
            ->whereIn('sub.type', ['T', 'P'])
            ->select('a.course_id', 'a.intake_id', 'a.subject_id', 'a.practical_time', 'sub.type')
            ->get()
            ->groupBy(fn($a) => $a->course_id . '|' . $a->intake_id);

        // 3) Minutes done per student/course/subject (time-of-day difference,
        //    wrapping past midnight — same as the Practical Card).
        $minutes = DB::table('subject_attendance_sessions')
            ->whereIn('student_id', $studentIds)
            ->whereIn('course_id', $courseIds)
            ->whereNull('checkpoint_type')
            ->whereNotNull('subject_id')
            ->whereNotNull('time_in')
            ->whereNotNull('time_out')
            ->groupBy('student_id', 'course_id', 'subject_id')
            ->select(
                'student_id', 'course_id', 'subject_id',
                DB::raw('SUM(FLOOR(MOD(TIME_TO_SEC(TIME(time_out)) - TIME_TO_SEC(TIME(time_in)) + 86400, 86400) / 60)) as mins')
            )
            ->get()
            ->keyBy(fn($m) => $m->student_id . '|' . $m->course_id . '|' . $m->subject_id);

        // 4) NVQ invoices + payments per student/course (returned invoices excluded).
        $nvq = DB::table('fee_invoices as f')
            ->join('paid_courses as pc', 'pc.invoice_id', '=', 'f.id')
            ->leftJoin('invoices_payments as p', 'p.invoice_id', '=', 'f.id')
            ->where('f.invoice_type', 'nvq')
            ->where('f.payment_status', '!=', 'returned')
            ->whereIn('f.student_id', $studentIds)
            ->groupBy('f.id', 'f.student_id', 'pc.course_id', 'pc.course_price')
            ->select(
                'f.id', 'f.student_id', 'pc.course_id', 'pc.course_price',
                DB::raw('COALESCE(SUM(p.amount), 0) as paid'),
                DB::raw('MAX(p.created_at) as last_paid_at')
            )
            ->get()
            ->groupBy(fn($r) => $r->student_id . '|' . $r->course_id);

        $minPercent = $this->minPercent($request);
        $rows = collect();

        foreach ($enrolments as $e) {
            $assigned = $assignments->get($e->course_id . '|' . $e->intake_id, collect());

            $theoryTotal = $theoryDone = $practicalTotal = $practicalDone = 0;
            $practiceRequired = $practiceDone = 0;

            foreach ($assigned->unique('subject_id') as $a) {
                $done = (int) optional($minutes->get($e->student_id . '|' . $e->course_id . '|' . $a->subject_id))->mins;

                if ($a->type === 'P') {
                    $planned = $this->plannedMinutes($a->practical_time);
                    $practicalTotal++;
                    $practiceRequired += $planned;
                    $practiceDone += $planned > 0 ? min($done, $planned) : 0;
                    if ($planned > 0 && $done >= $planned) {
                        $practicalDone++;
                    }
                } else {
                    $theoryTotal++;
                    if ($done > 0) {
                        $theoryDone++;
                    }
                }
            }

            $totalSubjects = $theoryTotal + $practicalTotal;
            $percent = $totalSubjects > 0 ? round((($theoryDone + $practicalDone) / $totalSubjects) * 100, 1) : 0.0;

            if ($percent <= $minPercent) {
                continue; // "above 75%"
            }

            // NVQ invoices may be raised against the original or the changed course.
            $invoices = collect()
                ->merge($nvq->get($e->student_id . '|' . $e->nvq_course_id, collect()))
                ->merge($e->change_course_id ? $nvq->get($e->student_id . '|' . $e->course_id, collect()) : collect())
                ->unique('id');

            $nvqAmount = $invoices->isNotEmpty()
                ? (float) $invoices->sum('course_price')
                : (float) ($e->course_nvq_amount ?? 0);
            $nvqPaid = (float) $invoices->sum('paid');
            $nvqDue = max(0, $nvqAmount - $nvqPaid);

            $nvqStatus = $nvqPaid <= 0 ? 'Not Paid' : ($nvqDue > 0 ? 'Partial' : 'Paid');

            if ($request->filled('nvq_status') && $request->nvq_status !== $nvqStatus) {
                continue;
            }

            $lastPaid = $invoices->pluck('last_paid_at')->filter()->max();

            $rows->push([
                'admission_number' => $e->admission_number,
                'student_name' => $e->student_name,
                'nic' => $e->national_id_number,
                'phone' => $e->phone_number,
                'course_name' => $e->course_name,
                'intake_name' => $e->intake_name ?? '-',
                'intake_start' => $e->intake_start ?? '-',
                'branch_name' => $e->branch_name ?? '-',
                'status' => $e->status,
                'theory_done' => $theoryDone,
                'theory_total' => $theoryTotal,
                'practical_done' => $practicalDone,
                'practical_total' => $practicalTotal,
                'practice_done' => $this->hhmm($practiceDone),
                'practice_required' => $this->hhmm($practiceRequired),
                'percent' => $percent,
                'nvq_amount' => $nvqAmount,
                'nvq_paid' => $nvqPaid,
                'nvq_due' => $nvqDue,
                'nvq_status' => $nvqStatus,
                'last_payment' => $lastPaid ? \Carbon\Carbon::parse($lastPaid)->format('Y-m-d') : null,
            ]);
        }

        return $rows->sortByDesc('percent')->values();
    }

    private function plannedMinutes($value): int
    {
        if ($value === null || $value === '') {
            return 0;
        }
        if (is_numeric($value)) {
            return (int) $value;
        }
        if (preg_match('/^(\d{1,3}):(\d{2})$/', trim((string) $value), $m)) {
            return ((int) $m[1] * 60) + (int) $m[2];
        }
        return 0;
    }

    private function hhmm(int $minutes): string
    {
        $minutes = max(0, $minutes);
        return sprintf('%02d:%02d', intdiv($minutes, 60), $minutes % 60);
    }
}
